def artifacts() -> dict[Path, str]:
    return {
        CONFIG_DIR / "design-tokens.css": build_css(),
        CONFIG_DIR / "tailwind.preset.js": build_tailwind(),
        CONFIG_DIR / "plotly-template-dark.json": json.dumps(
            build_plotly(DARK), indent=2
        )
        + "\n",
        CONFIG_DIR / "plotly-template-light.json": json.dumps(
            build_plotly(LIGHT), indent=2
        )
        + "\n",
        # Ships inside the package: an installed wheel renders a tearsheet
        # without needing the repo's config/ directory beside it.
        TEMPLATE_DIR / "tearsheet.css": build_print_css(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify committed artifacts match, without writing. Exit 1 on drift.",
    )
    args = parser.parse_args(argv)

    checks = assert_contrast()
    print(f"WCAG: {len(checks)} token pairs verified, all at or above AA.")

    drifted: list[Path] = []
    for path, content in artifacts().items():
        if args.check:
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != content:
                drifted.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO_ROOT)}")

    if drifted:
        print(
            "\nDESIGN TOKEN DRIFT — these files no longer match the generator:",
            file=sys.stderr,
        )
        for path in drifted:
            print(f"  {path.relative_to(REPO_ROOT)}", file=sys.stderr)
        print(
            "\nA generated file was edited by hand. Change the tokens in "
            f"{GENERATED_BY} and re-run it.",
            file=sys.stderr,
        )
        return 1
    if args.check:
        print("Design tokens are in sync.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
