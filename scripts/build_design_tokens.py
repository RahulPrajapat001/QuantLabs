"""Single source of truth for the QuantLab design system's tokens.

``docs/DESIGN_SYSTEM.md`` is binding, and a binding document that is transcribed
by hand into two frontends stops being binding the first time someone types a hex
code. So the tokens are defined **here, once**, and every consumable artifact is
generated:

* ``config/design-tokens.css``       — CSS custom properties (Next.js, Streamlit)
* ``config/tailwind.preset.js``      — Tailwind preset (Next.js)
* ``config/plotly-template-dark.json`` / ``-light.json`` — Plotly templates

Run ``python scripts/build_design_tokens.py`` to regenerate; run it with
``--check`` to verify the committed artifacts match (this is what CI does, via
``tests/design/test_design_tokens.py``). A pull request that hand-edits a
generated file fails.

**Contrast is computed, not claimed.** :func:`verify_contrast` walks every
foreground/background pair the design system permits and returns the WCAG ratio.
The build refuses to emit anything if a pair falls below AA. "Verified at WCAG
AA" is otherwise exactly the kind of unfalsifiable assertion this project exists
to avoid.

The chart palettes were additionally validated for colour-vision deficiency
separation, lightness banding, chroma floor and surface contrast; the recorded
results are in ``docs/DESIGN_SYSTEM.md``.
"""

