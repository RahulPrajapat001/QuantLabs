# --- Contrast verification ----------------------------------------------------


@dataclass(frozen=True, slots=True)
class ContrastCheck:
    mode: str
    foreground: str
    background: str
    ratio: float
    required: float

    @property
    def passes(self) -> bool:
        return self.ratio >= self.required

    def render(self) -> str:
        verdict = "PASS" if self.passes else "FAIL"
        return (
            f"[{verdict}] {self.mode:5s} {self.foreground:16s} on "
            f"{self.background:16s} {self.ratio:5.2f}:1 (needs {self.required})"
        )


def _text_tokens(mode: Mode) -> Iterator[tuple[str, str, float]]:
    """Every foreground token, with the level it must clear."""

    for name in ("text-primary", "text-secondary", "text-muted"):
        yield name, mode.neutral[name], AA_NORMAL
    for name, value in mode.semantic.items():
        # Semantic colours carry numbers (a return, a p-value), so they are body
        # text and must clear AA normal, not the 3:1 UI-component level.
        yield name, value, AA_NORMAL


def verify_contrast() -> list[ContrastCheck]:
    """Every text-on-surface pair the system permits, with its measured ratio."""

    checks: list[ContrastCheck] = []
    surface_names = ("bg", "surface", "surface-raised")
    for mode in MODES:
        for fg_name, fg, required in _text_tokens(mode):
            for bg_name in surface_names:
                checks.append(
                    ContrastCheck(
                        mode=mode.name,
                        foreground=fg_name,
                        background=bg_name,
                        ratio=contrast_ratio(fg, mode.neutral[bg_name]),
                        required=required,
                    )
                )
        # Borders are non-text UI boundaries: AA large is the applicable level.
        for border in ("border", "border-strong"):
            checks.append(
                ContrastCheck(
                    mode=mode.name,
                    foreground=border,
                    background="bg",
                    ratio=contrast_ratio(mode.neutral[border], mode.neutral["bg"]),
                    required=1.0 if border == "border" else AA_LARGE,
                )
            )
    return checks


class ContrastError(RuntimeError):
    """Raised when a token pair falls below its WCAG level."""


def assert_contrast() -> list[ContrastCheck]:
    checks = verify_contrast()
    failures = [c for c in checks if not c.passes]
    if failures:
        raise ContrastError(
            "the palette does not meet WCAG AA:\n"
            + "\n".join(f.render() for f in failures)
            + "\n\nFix the token, do not lower the threshold."
        )
    return checks


# --- Emitters -----------------------------------------------------------------


def _css_block(mode: Mode, selector: str) -> list[str]:
    lines = [f"{selector} {{"]
    lines.append("  /* neutral scale — one hue family */")
    for name, value in mode.neutral.items():
        lines.append(f"  --ql-{name}: {value};")
    lines.append("  /* semantic — colour encodes meaning, never decoration */")
    for name, value in mode.semantic.items():
        lines.append(f"  --ql-{name}: {value};")
    lines.append("  /* chart palettes */")
    for i, value in enumerate(mode.categorical, start=1):
        lines.append(f"  --ql-series-{i}: {value};")
    for i, value in enumerate(mode.sequential, start=1):
        lines.append(f"  --ql-seq-{i}: {value};")
    for i, value in enumerate(mode.diverging, start=1):
        lines.append(f"  --ql-div-{i}: {value};")
    lines.append("}")
    return lines


def build_css() -> str:
    lines = [
        "/*",
        " * QuantLab design tokens.",
        *[f" * {line}" for line in DO_NOT_EDIT_LINES],
        " *",
        " * Consumed by the Next.js frontend and the Streamlit dashboard so both",
        " * render identical colour. Never write a literal hex in a component.",
        " */",
        "",
    ]
    lines += _css_block(DARK, ':root, [data-theme="dark"]')
    lines.append("")
    lines += _css_block(LIGHT, '[data-theme="light"]')
    lines.append("")
    lines.append(":root {")
    lines.append("  /* spacing — 4px base, dense by intent */")
    for name, value in SPACING.items():
        lines.append(f"  --ql-space-{name}: {value};")
    lines.append("  /* type scale — size and its line height travel together */")
    for name, (size, height) in TYPE_SCALE.items():
        lines.append(f"  --ql-text-{name}: {size};")
        lines.append(f"  --ql-leading-{name}: {height};")
    lines.append("  /* typography */")
    lines.append(f"  --ql-font-sans: {FONT_SANS};")
    lines.append(f"  --ql-font-mono: {FONT_MONO};")
    lines.append("  /* layout */")
    for name, value in DIMENSIONS.items():
        lines.append(f"  --ql-{name}: {value};")
    lines.append("}")
    lines.append("")
    lines.append("/*")
    lines.append(" * The rule that does more for credibility than any other: every")
    lines.append(" * number in the product is monospace with tabular figures, so")
    lines.append(" * digits align in a column and magnitudes are comparable by eye.")
    lines.append(" */")
    lines.append(".ql-num {")
    lines.append("  font-family: var(--ql-font-mono);")
    lines.append("  font-variant-numeric: tabular-nums;")
    lines.append('  font-feature-settings: "tnum" 1, "zero" 1;')
    lines.append("  letter-spacing: 0;")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def build_tailwind() -> str:
    def var(name: str) -> str:
        return f"var(--ql-{name})"

    colours: dict[str, Any] = {
        name: var(name)
        for name in (
            "bg",
            "surface",
            "surface-raised",
            "border",
            "border-strong",
            "text-primary",
            "text-secondary",
            "text-muted",
            "positive",
            "negative",
            "warning",
            "info",
            "benchmark",
        )
    }
    colours["series"] = {
        str(i): var(f"series-{i}") for i in range(1, len(DARK.categorical) + 1)
    }
    colours["seq"] = {
        str(i): var(f"seq-{i}") for i in range(1, len(DARK.sequential) + 1)
    }
    colours["div"] = {
        str(i): var(f"div-{i}") for i in range(1, len(DARK.diverging) + 1)
    }

    spacing = {name: var(f"space-{name}") for name in SPACING}
    font_size = {
        name: [var(f"text-{name}"), {"lineHeight": var(f"leading-{name}")}]
        for name in TYPE_SCALE
    }

    theme = {
        "colors": colours,
        "spacing": spacing,
        "fontSize": font_size,
        "fontFamily": {
            "sans": [var("font-sans")],
            "mono": [var("font-mono")],
        },
        "borderRadius": {"DEFAULT": var("radius"), "none": "0px"},
        "maxHeight": {"metric-card": var("metric-card-max-height")},
        "height": {
            "table-row": var("table-row-height"),
            "table-header": var("table-header-height"),
        },
        "width": {"sidebar": var("sidebar-width")},
    }

    body = json.dumps(theme, indent=2)
    return (
        f"// QuantLab Tailwind preset. {DO_NOT_EDIT}\n"
        "//\n"
        "// Every value resolves to a CSS custom property from\n"
        "// config/design-tokens.css, so light and dark modes are a single\n"
        "// data-theme swap and no colour is duplicated between the two files.\n"
        "//\n"
        "// `theme` (not `theme.extend`) on colors and spacing is deliberate: it\n"
        "// REPLACES Tailwind's default palette rather than adding to it, so\n"
        "// `bg-red-500` and `p-7` stop existing. Ad-hoc colour and spacing become\n"
        "// build errors instead of review comments.\n"
        "\n"
        "/** @type {import('tailwindcss').Config} */\n"
        f"module.exports = {{\n  theme: {body},\n}};\n"
    )


def _axis(mode: Mode, *, grid: bool) -> dict[str, Any]:
    """FT/Economist axis: no chart frame, no vertical grid, recessive everything."""

    axis: dict[str, Any] = {
        "showgrid": grid,
        "zeroline": False,
        "showline": False,
        "ticks": "outside",
        "ticklen": 4,
        "tickcolor": mode.neutral["border"],
        "tickfont": {
            "family": FONT_MONO,
            "size": 11,
            "color": mode.neutral["text-muted"],
        },
        "title": {
            "font": {
                "family": FONT_SANS,
                "size": 11,
                "color": mode.neutral["text-secondary"],
            }
        },
        "automargin": True,
    }
    if grid:
        axis["gridcolor"] = mode.neutral["border"]
        axis["gridwidth"] = 1
    return axis


def build_plotly(mode: Mode) -> dict[str, Any]:
    return {
        "data": {
            "scatter": [
                {
                    "line": {"width": 2},
                    "marker": {"size": 8},
                    "hoverlabel": {
                        "font": {"family": FONT_MONO, "size": 11},
                        "bgcolor": mode.neutral["surface-raised"],
                        "bordercolor": mode.neutral["border-strong"],
                    },
                }
            ],
            "bar": [
                {
                    "marker": {"line": {"width": 0}},
                    "hoverlabel": {"font": {"family": FONT_MONO, "size": 11}},
                }
            ],
            "heatmap": [
                {
                    "colorscale": [
                        [i / (len(mode.diverging) - 1), c]
                        for i, c in enumerate(mode.diverging)
                    ],
                    "showscale": True,
                }
            ],
        },
        "layout": {
            # layout.meta is Plotly's sanctioned slot for arbitrary user data.
            # A top-level "_comment" is not: Template() rejects it outright.
            "meta": {"generated_by": GENERATED_BY, "notice": DO_NOT_EDIT},
            "colorway": list(mode.categorical),
            "paper_bgcolor": mode.neutral["surface"],
            "plot_bgcolor": mode.neutral["surface"],
            "font": {
                "family": FONT_SANS,
                "size": 12,
                "color": mode.neutral["text-secondary"],
            },
            "title": {
                "font": {
                    "family": FONT_SANS,
                    "size": 14,
                    "color": mode.neutral["text-primary"],
                },
                "x": 0,
                "xanchor": "left",
                "pad": {"b": 8},
            },
            # Horizontal y grid only. A vertical grid on a time axis adds ink
            # without adding a readable comparison.
            "xaxis": _axis(mode, grid=False),
            "yaxis": _axis(mode, grid=True),
            "margin": {"l": 56, "r": 16, "t": 32, "b": 40},
            # Direct labelling is the default (FT convention); when a chart does
            # show a legend it sits above the plot, horizontal, unboxed.
            "legend": {
                "orientation": "h",
                "yanchor": "bottom",
                "y": 1.02,
                "xanchor": "left",
                "x": 0,
                "bgcolor": "rgba(0,0,0,0)",
                "borderwidth": 0,
                "font": {
                    "family": FONT_SANS,
                    "size": 11,
                    "color": mode.neutral["text-secondary"],
                },
            },
            "hovermode": "x unified",
            "hoverlabel": {
                "font": {"family": FONT_MONO, "size": 11},
                "bgcolor": mode.neutral["surface-raised"],
                "bordercolor": mode.neutral["border-strong"],
            },
            # Only real Plotly layout keys belong here. The semantic colours a
            # chart needs (benchmark grey, positive/negative) are NOT smuggled in
            # as an invented layout key — Plotly silently misparses the whole
            # layout when it meets one. They come from config/design-tokens.css,
            # which is the single source both frontends already read.
            "separators": ".,",
            "showlegend": False,
        },
    }


