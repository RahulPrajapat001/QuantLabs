@dataclass(frozen=True, slots=True)
class Mode:
    """One colour mode. Both modes draw their neutrals from a single hue family."""

    name: str
    neutral: Mapping[str, str]
    semantic: Mapping[str, str]
    #: Fixed-order categorical slots. Never cycled; a 6th series folds into
    #: "Other", small multiples, or a composite encoding.
    categorical: tuple[str, ...]
    #: Single-hue magnitude ramp, ordered low value -> high value. It runs
    #: monotonically *away from this mode's surface*: light -> dark on a light
    #: surface, dark -> light on a dark one. A dark mode is re-stepped from the
    #: same hue, never an inverted copy of the light ramp.
    sequential: tuple[str, ...]
    #: Polarity ramp: negative pole -> neutral grey midpoint -> positive pole.
    diverging: tuple[str, ...]

    @property
    def surfaces(self) -> tuple[str, ...]:
        return (
            self.neutral["bg"],
            self.neutral["surface"],
            self.neutral["surface-raised"],
        )


