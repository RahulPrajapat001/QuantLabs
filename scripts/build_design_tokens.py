# --- WCAG ---------------------------------------------------------------------

#: Normal-size body text. Every text/background pair must clear this.
AA_NORMAL = 4.5
#: Large text (>=18.66px bold / >=24px) and non-text UI boundaries.
AA_LARGE = 3.0


def _channel(value: int) -> float:
    c = value / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def relative_luminance(hex_colour: str) -> float:
    """WCAG 2.1 relative luminance of an sRGB hex colour."""

    raw = hex_colour.lstrip("#")
    if len(raw) != 6:
        raise ValueError(f"expected a 6-digit hex colour, got {hex_colour!r}")
    r, g, b = (int(raw[i : i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * _channel(r) + 0.7152 * _channel(g) + 0.0722 * _channel(b)


def contrast_ratio(foreground: str, background: str) -> float:
    """WCAG 2.1 contrast ratio between two sRGB hex colours."""

    a, b = relative_luminance(foreground), relative_luminance(background)
    lighter, darker = max(a, b), min(a, b)
    return (lighter + 0.05) / (darker + 0.05)


