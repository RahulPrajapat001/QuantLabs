"""Generate ``docs/data_dictionary.md`` from the feature registry.

Generated, not written. The registry already holds every feature's name,
category, lookback, dependencies and description — a hand-maintained table would
be a second copy of that, and the copy would be wrong within a week of anyone
adding a feature.

    python scripts/build_data_dictionary.py           # write the file
    python scripts/build_data_dictionary.py --check   # CI: fail on drift

The ``--check`` mode is the mechanism that keeps the claim true: adding a feature
without regenerating fails the build, exactly as the design-token generator does
for colour.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

from quantlab.feature_engineering.registry import REGISTRY, FeatureKind, FeatureSpec

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT = REPO_ROOT / "docs" / "data_dictionary.md"

BANNER = (
    "<!-- GENERATED by scripts/build_data_dictionary.py — do not edit by hand.\n"
    "     Edit the feature's `description=` at its registration site in\n"
    "     src/quantlab/feature_engineering/definitions/ and re-run the script. -->"
)

HEADER = """# Data dictionary

Every feature in the registry, with what it measures, the history it needs before
its first valid value, and what it is computed from.

**Lookback** is the number of trailing bars required before the feature has a
defined value. A feature with lookback 20 is `NaN` for the first 19 bars of a
security's history — that gap is real and the backtester respects it via the
strategy `warmup`. Cross-sectional features have lookback 0: they need no history
of their own, only their input's.

**Kind** distinguishes `time_series` (computed per security from its own trailing
window) from `cross_sectional` (computed across the point-in-time universe on each
date). The distinction matters for correctness: a cross-sectional feature cannot
be computed from one security in isolation, and its value depends on which
securities were index members that day.

Every feature here is verified look-ahead-free by
`tests/feature_engineering/test_lookahead.py`, which computes each one on the full
series and on the series truncated at *t* and asserts the values at *t* are equal.
That test runs over the whole registry, not a sample.
"""


def _rows(specs: list[FeatureSpec]) -> str:
    lines = [
        "| Feature | Description | Lookback | Depends on |",
        "|---|---|---:|---|",
    ]
    for spec in specs:
        description = " ".join((spec.description or "").split()) or "—"
        depends = ", ".join(f"`{d}`" for d in spec.dependencies) or "—"
        lines.append(f"| `{spec.name}` | {description} | {spec.lookback} | {depends} |")
    return "\n".join(lines)


def render() -> str:
    specs = sorted(REGISTRY.all(), key=lambda s: (s.category, s.name))

    by_category: dict[str, list[FeatureSpec]] = defaultdict(list)
    for spec in specs:
        by_category[spec.category].append(spec)

    parts = [BANNER, "", HEADER, ""]

    parts.append("## Summary")
    parts.append("")
    parts.append("| Category | Features | Kind |")
    parts.append("|---|---:|---|")
    for category, members in sorted(by_category.items()):
        kinds = sorted({str(m.kind.value) for m in members})
        parts.append(f"| {category} | {len(members)} | {', '.join(kinds)} |")
    parts.append(f"| **Total** | **{len(specs)}** | |")
    parts.append("")

    for category, members in sorted(by_category.items()):
        cross = all(m.kind is FeatureKind.CROSS_SECTIONAL for m in members)
        parts.append(f"## {category}")
        parts.append("")
        if cross:
            parts.append(
                "_Cross-sectional: computed across the point-in-time universe on "
                "each date, so a value depends on that date's index membership._"
            )
            parts.append("")
        parts.append(_rows(members))
        parts.append("")

    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "Exit non-zero if the committed file differs from what would be generated."
        ),
    )
    args = parser.parse_args(argv)

    generated = render()

    if args.check:
        if not OUTPUT.exists():
            print(f"{OUTPUT} does not exist. Run: python {Path(__file__).name}")
            return 1
        current = OUTPUT.read_text(encoding="utf-8")
        if current != generated:
            print(
                f"{OUTPUT} is out of date — a feature was added, removed or "
                f"re-described without regenerating.\n"
                f"Run: python scripts/build_data_dictionary.py"
            )
            return 1
        print(f"{OUTPUT} is in sync ({len(REGISTRY.all())} features).")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)} ({len(REGISTRY.all())} features)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
